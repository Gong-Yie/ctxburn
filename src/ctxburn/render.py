LANGS = tuple(_S)
CHARTS = ("flame", "bar", "line", "pie")


def _tok(v: int) -> str:
    if v >= 1_000_000:
        return f"{v / 1_000_000:.1f}M"
    if v >= 1_000:
        return f"{v / 1_000:.1f}k"
    return str(v)


def summary_line(r: Report, lang: str = "en") -> str:
    s = _S.get(lang, _S["en"])
    if not r.n_calls:
        return s["no_calls"]
    return s["summary"].format(
        pct=f"{r.replay_ratio:.0%}", calls=r.n_calls, growth=f"{r.context_growth:.1f}x"
    )


def render_html(
    report: Report, title: str | None = None, lang: str = "en", chart: str = "flame"
) -> str:
    r = report
    lang = lang if lang in _S else "en"
    chart = chart if chart in CHARTS else "flame"
    s = _S[lang]
    data = r.to_dict()
    data["hues"] = _HUE
    data["chart"] = chart
    data["ui"] = {
        k: s[k]
        for k in (
            "tip_replay",
            "tip_fresh",
            "tip_cached",
            "tip_first",
            "avg",
            "total",
            "legend_replay",
            "hint_flame",
            "hint_bar",
            "hint_line",
            "hint_pie",
        )
    }
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    headline = title or f"ctxburn · {r.name}"

    total_kind = sum(v[0] for v in data["by_kind"].values()) or 1
    kind_rows = "".join(
        f'<tr><td><span class="dot" style="background:hsl({_HUE.get(k, 0)} 70% 55%)"></span>{k}</td>'
        f"<td class='num'>{v[0]:,}</td>"
        f"<td class='num'>{v[0] / total_kind:.0%}</td>"
        f"<td class='num'>{(v[1] / v[0] if v[0] else 0):.0%}</td></tr>"
        for k, v in sorted(data["by_kind"].items(), key=lambda kv: -kv[1][0])
    )

    top_total = r.total_input_tokens or 1

    def _top_row(seg: dict) -> str:
        hue = _HUE.get(seg["kind"], 0)
        return (
            f'<tr><td><span class="dot" style="background:hsl({hue} 70% 55%)"></span>'
            f'<code>{seg["kind"]}</code> <span class="dim">{escape(seg["preview"])}</span></td>'
            f'<td class="num">{int(seg["tokens"]):,}</td>'
            f'<td class="num">{seg["tokens"] / top_total:.0%}</td>'
            f'<td class="num">{seg["sends"]}×</td>'
            f'<td class="num">{seg["replays"]}×</td>'
            f"</tr>"
        )

    tabs = "".join(
        f'<button class="tab{" on" if c == chart else ""}" data-chart="{c}">'
        f"{s[f'chart_{c}']}</button>"
        for c in CHARTS
    )

    html = _TEMPLATE
    html = html.replace("@@LANG@@", lang)
    html = html.replace("@@SUMMARY@@", summary_line(r, lang))
    html = html.replace("@@TITLE@@", escape(headline))
    html = html.replace("@@INPUT@@", f"{r.total_input_tokens:,}")
    html = html.replace("@@REPLAY_PCT@@", f"{r.replay_ratio:.0%}")
    html = html.replace("@@REPLAY@@", f"{r.replay_tokens:,}")
    html = html.replace("@@FRESH@@", f"{r.fresh_tokens:,}")
    html = html.replace("@@OUTPUT@@", f"{r.total_output_tokens:,}")
    html = html.replace("@@CALLS@@", str(r.n_calls))
    html = html.replace("@@GROWTH@@", f"{r.context_growth:.1f}x")
    html = html.replace("@@TABS@@", tabs)
    html = html.replace("@@KINDROWS@@", kind_rows)
    html = html.replace("@@TOP_ROWS@@", "".join(_top_row(seg) for seg in r.top_segments))
    html = html.replace("@@WARN@@", "".join(f'<div class="warn">{escape(n)}</div>' for n in r.notes))
    html = html.replace(
        "@@FOOTER@@",
        s["footer"].format(
            calls=r.n_calls,
            intok=f"{r.total_input_tokens:,}",
            replay=f"{r.replay_tokens:,}",
        ),
    )
    for key, value in s.items():
        html = html.replace(f"@@{key.upper()}@@", value)
    html = html.replace("@@DATA@@", payload.replace("</", "<\\/"))
    return html


